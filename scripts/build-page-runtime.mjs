#!/usr/bin/env node
/**
 * Bundles the browser page runtime (src/browser-runtime/page) into one IIFE string that the
 * main process evaluates in a page's isolated world. Output is committed:
 *   src/main/browser/page-runtime.generated.ts
 * Run after changing anything under src/browser-runtime/page:
 *   node scripts/build-page-runtime.mjs
 * scripts/tests/page-runtime-fresh.test.mjs fails when the committed file is stale.
 */
import { rolldown } from 'rolldown'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

export const ENTRY = 'src/browser-runtime/page/entry.ts'
export const OUTPUT = 'src/main/browser/page-runtime.generated.ts'

export async function buildPageRuntime(root = process.cwd()) {
  const bundle = await rolldown({ input: join(root, ENTRY), platform: 'browser', logLevel: 'silent', treeshake: true })
  const { output } = await bundle.generate({ format: 'iife', minify: true, comments: false })
  await bundle.close()
  const code = output[0].code.trim()
  return [
    '// GENERATED by scripts/build-page-runtime.mjs from src/browser-runtime/page — do not edit.',
    '// Includes code from microsoft/playwright (Apache-2.0), see src/browser-runtime/page/vendor/playwright/NOTICE.',
    `export const PAGE_RUNTIME_SOURCE = ${JSON.stringify(code)}`,
    '',
  ].join('\n')
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const root = process.cwd()
  const next = await buildPageRuntime(root)
  const target = join(root, OUTPUT)
  let prev = ''
  try {
    prev = readFileSync(target, 'utf8')
  } catch {
    // first build
  }
  if (prev === next) console.log(`[page-runtime] up to date (${next.length} bytes)`)
  else {
    writeFileSync(target, next)
    console.log(`[page-runtime] wrote ${OUTPUT} (${next.length} bytes)`)
  }
}
